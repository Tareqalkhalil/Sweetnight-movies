// تقسيم البيانات إلى دفعات
function chunkArray(array, size) {
  const chunks = []
  for (let i = 0; i < array.length; i += size) {
    chunks.push(array.slice(i, i + size))
  }
  return chunks
}

// استيراد دفعة واحدة
async function importBatch(titles, batchNumber, totalBatches) {
  try {
    console.log(`\n📤 استيراد الدفعة ${batchNumber}/${totalBatches} (${titles.length} مسلسل)...`)
    
    const response = await fetch(API_URL, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        titles: titles,
        contentType: 'series', // نوع المحتوى: مسلسلات
        categorySlug: 'foreign-series', // الفئة: مسلسلات أجنبية
        limit: 1,
      })
    })

    if (!response.ok) {
      const error = await response.json()
      throw new Error(error.message || 'خطأ في API')
    }

    const data = await response.json()
    const imported = data.imported ?? data.count ?? 0
    const skipped = data.skipped ?? 0
    const failed = data.failed ?? 0

    console.log(`✅ الدفعة ${batchNumber}: تم بنجاح`)
    console.log(`   - المستورد: ${imported}`)
    console.log(`   - المكرر: ${skipped}`)
    console.log(`   - الأخطاء: ${failed}`)
    
    return {
      batchNumber,
      imported,
      skipped,
      failed
    }
  } catch (error) {
    console.error(`❌ خطأ في الدفعة ${batchNumber}: ${error.message}`)
    return {
      batchNumber,
      imported: 0,
      skipped: 0,
      failed: titles.length,
      error: error.message
    }
  }
}

// البرنامج الرئيسي
async function main() {
  console.log('🚀 بدء استيراد 568 مسلسل')
  console.log('═'.repeat(60))
  console.log(`📊 إجمالي المسلسلات: ${SERIES_LIST.length}`)
  
  // التحقق من توفر الـ API
  try {
    const healthCheck = await fetch('http://localhost:3001/api/admin/import-topcinema', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ titles: [], contentType: 'series' })
    })
    
    if (healthCheck.status !== 400 && healthCheck.status !== 401) {
      throw new Error('API غير متاح')
    }
  } catch (error) {
    console.error('❌ خطأ: الـ API غير متاح على http://localhost:3001')
    console.error('تأكد من تشغيل الموقع: npm run dev')
    process.exit(1)
  }

  // تقسيم المسلسلات إلى دفعات (50 مسلسل في كل دفعة)
  const batches = chunkArray(SERIES_LIST, 50)
  console.log(`📦 تم تقسيم البيانات إلى ${batches.length} دفعة`)
  console.log('═'.repeat(60))

  const results = []
  let totalImported = 0
  let totalSkipped = 0
  let totalFailed = 0

  // استيراد كل دفعة
  for (let i = 0; i < batches.length; i++) {
    const batch = batches[i]
    const result = await importBatch(batch, i + 1, batches.length)
    results.push(result)
    
    totalImported += result.imported
    totalSkipped += result.skipped
    totalFailed += result.failed

    // تأخير صغير بين الدفعات لتجنب الحمل الزائد
    if (i < batches.length - 1) {
      await new Promise(resolve => setTimeout(resolve, 1000))
    }
  }

  // عرض النتائج النهائية
  console.log('\n' + '═'.repeat(60))
  console.log('📊 النتائج النهائية')
  console.log('═'.repeat(60))
  console.log(`✅ تم استيراد: ${totalImported} مسلسل`)
  console.log(`⚠️  تم تخطي (مكرر): ${totalSkipped} مسلسل`)
  console.log(`❌ فشل: ${totalFailed} مسلسل`)
  console.log(`📈 النسبة الناجحة: ${((totalImported / SERIES_LIST.length) * 100).toFixed(2)}%`)
  console.log('═'.repeat(60))

  // عرض ملخص الدفعات
  console.log('\n📋 ملخص الدفعات:')
  results.forEach(r => {
    if (r.error) {
      console.log(`  الدفعة ${r.batchNumber}: ❌ ${r.error}`)
    } else {
      console.log(`  الدفعة ${r.batchNumber}: ✅ ${r.imported} | ⚠️ ${r.skipped} | ❌ ${r.failed}`)
    }
  })

  console.log('\n🎉 انتهى الاستيراد!')
  console.log(`⏱️  الوقت: ${new Date().toLocaleString('ar-EG')}`)
}

// تشغيل البرنامج
main().catch(console.error)
